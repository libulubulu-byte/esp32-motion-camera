/**
 * @file version.h
 * @brief ★★★ 固件版本的唯一来源（要改版本号只改这一个文件）★★★
 *
 * ---------------------------------------------------------------------------
 * OTA 升级的完整规则（看这一段就够，别再去别处找版本号）
 * ---------------------------------------------------------------------------
 *
 * 只要满足下面这一条，设备下次上电就会自动升级：
 *
 *        服务器上 .bin 镜像头里的版本   >   本机 SNAP_FW_VERSION
 *
 * "服务器上镜像头里的版本" 不是你手填的，而是 server.py 直接从 .bin 里读出来的
 * （rest_mock_server/server.py 的 read_image_version()，读 esp_app_desc_t.version），
 * 而那个字段又由顶层 CMakeLists.txt 强制对齐到本文件的 SNAP_FW_VERSION。
 * 所以整条链是： **本文件 SNAP_FW_VERSION → 镜像头 → server.py 读出来 → ota.json**
 * 四处天然一致，不存在"忘了同步某个 JSON"的可能。
 *
 * 【怎么升级】三步，一步都不能少：
 *   1. 改下面 SNAP_FW_VERSION 为更大的号（如 "0.1.0" -> "0.1.1"）；
 *   2. idf.py build           （新镜像头的版本 = 新号）
 *   3. python publish_firmware.py   （把新 .bin 复制到 rest_mock_server/firmware/）
 *   4. 复位设备（OTA 检查在上电时做一次；不重新上电不会重查）
 *
 * 【只升不降】服务器版本 <= 本机版本时一律跳过。所以刷错版本后**无法**用这个
 *   机制退回去，只能手工烧录。这是刻意的设计（防止服务器上放着旧固件把设备降级）。
 *
 * 【绝对不能写的东西】版本号必须是**纯数字用点分隔**：0.1.1 / 1.2 / 1.2.3.4 可以。
 *   不能写 "0.1.1-rc1"（预发布后缀）、"v0.1.1"（前导 v）、含 git 短哈希的字符串。
 *   原因：ota_check.c 的格式守卫会直接拒掉这类清单，而且历史上用 IDF 默认的
 *   git describe 版本（形如 "676dc691-dirty"）会被解析成 676.0.0 ——
 *   恒大于本机版本 ⇒ **每次上电都刷同一个镜像，无限重启**，非常难排查。
 *   顶层 CMakeLists.txt 已加 FATAL_ERROR 守卫，写错了直接编译失败，不会带病出厂。
 *
 * 【为什么不用 SNAP_FW_VERSION_NUM 比较】见 main/app_version.h：改成两边都用
 *   可读字符串、靠解析比大小，就少了一个"改版本时容易忘记同步"的整数。
 * ---------------------------------------------------------------------------
 */

